#pragma once
#include <cstdint>

namespace ascend_deepep::combine_diagnostics {
// One 576B record per AIV, independent of EP/token/chunk counts. This is a
// separate ABI from the optional legacy V46 per-peer/chunk timeline.
constexpr uint32_t kVersion = 4, kMagic = 0x434d4250, kCores = 64, kWords = 72;
constexpr uint32_t kUbBytes = kWords * sizeof(uint64_t);
enum Field : uint32_t {
    Magic = 0,
    Version,
    Rank,
    Core,
    World,
    Tokens,
    Role,
    WithWeights,
    Sample,
    Begin,
    InitDone,
    ProducerBegin,
    ProducerEnd,
    SourceBegin,
    SourceEnd,
    QuietBegin,
    QuietEnd,
    ReturnsBegin,
    ReturnsEnd,
    WeightWaitBegin,
    WeightWaitEnd,
    End,
    WeightSendBegin,
    WeightSendEnd,
    GatherWaitTicks,
    GatewayReduceTicks,
    LocalReduceWaitTicks,
    CrossReduceWaitTicks,
    CrossSubmitTicks,
    CrossBarrierTicks,
    SourceWaitTicks,
    GatewayTokens,
    GatewayRows,
    DirectRows,
    ReducedRows,
    PayloadWqes,
    CompletionSos,
    GatewayReadBytes,
    GatewayWriteBytes,
    FinalTokens,
    FinalRows,
    FinalReadBytes,
    FinalWriteBytes,
    ControlLoadTicks,
    Groups,
    Chunks,
    ChunkTokens,
    CrossCores,
    Topk,
    FirstDirectIssue,
    FirstReducedIssue,
    GatherEnd,
    LocalReturnBegin,
    LocalReturnEnd,
    SourceFlagsWaitTicks,
    SourceBarrierTicks,
    PeerExportTicks,
    SqPressureCount,
    CreditSos,
    CreditQuietCount,
    CreditWaitTicks,
    CrossPeerSetupTicks,
    CrossSoReserveTicks,
    Lane0PayloadRows,
    Lane1PayloadRows,
    Lane0CreditWaitTicks,
    Lane1CreditWaitTicks,
    Lane0QuietTicks,
    Lane1QuietTicks,
    Lane0SqPressureCount,
    Lane1SqPressureCount,
    FieldCount
};
enum CoreRole : uint32_t { Local = 0, Cross = 1, Gateway = 2, Idle = 3 };
static_assert(FieldCount <= kWords);
}  // namespace ascend_deepep::combine_diagnostics
